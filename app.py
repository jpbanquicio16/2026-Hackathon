def choose_dataset() -> tuple[bytes, str, str] | None:
    """Returns (bytes, display name, dataset key); None while waiting for an upload."""
    st.subheader("Data")
    source = st.radio(
        "Data source",
        ["Sample dataset", "Upload a CSV"],
        key="source",
        label_visibility="collapsed",
    )
    if source == "Sample dataset":
        st.caption(
            "Synthetic results from a traffic-sign classifier on 1,200 images, "
            "generated by `scripts/make_sample_data.py`."
        )
        return SAMPLE_PATH.read_bytes(), SAMPLE_PATH.name, "sample"
    upload = st.file_uploader(
        "CSV of predictions",
        type=["csv"],
        key="upload",
        help="One row per evaluated example, with a header row.",
    )
    if upload is None:
        return None
    # A fresh upload gets a fresh key, even if it is the same file, so no
    # choices from the previous dataset carry over.
    return upload.getvalue(), upload.name, f"upload:{upload.file_id}"


def map_settings() -> Settings:
    st.subheader("Map settings")
    n_bins = st.select_slider(
        "Ranges per axis",
        options=list(range(2, 9)),
        value=A.DEFAULT_BINS,
        key="n_bins",
        help="Each feature is split into this many equal-width ranges. "
        "Changing it clears the selected cell.",
    )
    small_n = st.number_input(
        "Small-sample threshold",
        min_value=2,
        max_value=100_000,
        value=A.DEFAULT_SMALL_SAMPLE,
        step=1,
        key="small_n",
        help="Cells with fewer examples than this are marked as small samples, "
        "because their error rates are unreliable.",
    )
    return Settings(int(n_bins), int(small_n))


