def show_rows(
    raw: pd.DataFrame,
    evaluation: A.Evaluation,
    index: pd.Index,
    roles: Roles,
    lead: tuple[str, ...],
    numeric: tuple[str, ...],
) -> pd.DataFrame:
    """The detail table: original columns, mapped columns first."""
    confidence = (roles.confidence,) if roles.confidence_ok else ()
    lead_columns = (*roles.ids, roles.actual, roles.predicted, *lead, *confidence)
    table = A.detail_table(raw, evaluation.rows["is_error"], index, lead_columns, (*numeric, *confidence))
    column_config = {
        table.columns[0]: st.column_config.NumberColumn(
            format="%d", help="Row number in the file (1 = first row after the header)."
        )
    }
    if confidence:
        column_config[roles.confidence] = st.column_config.ProgressColumn(
            min_value=0.0, max_value=1.0, format="%.2f", help="Probability the model gave to its predicted class."
        )
    st.dataframe(table, hide_index=True, column_config=column_config)
    return table


def inspect_section(
    raw: pd.DataFrame,
    evaluation: A.Evaluation,
    fmap: A.FailureMap,
    roles: Roles,
    numeric: tuple[str, ...],
    settings: Settings,
) -> A.CellStats | None:
    st.header("4 · Inspect a cell", divider="gray")
    left, middle, right = st.columns([5, 5, 2], vertical_alignment="bottom")
    with left:
        sel_x = st.selectbox(
            f"{md(fmap.x_col)} range",
            list(range(len(fmap.x_bins))),
            index=None,
            format_func=lambda i: fmap.x_bins.labels[i],
            placeholder="Choose a range",
            key="sel_x",
        )
    with middle:
        sel_y = st.selectbox(
            f"{md(fmap.y_col)} range",
            list(range(len(fmap.y_bins))),
            index=None,
            format_func=lambda i: fmap.y_bins.labels[i],
            placeholder="Choose a range",
            key="sel_y",
        )
    with right:
        errors_only = st.toggle(
            "Errors only",
            key="errors_only",
            help="Show only mistaken rows. The selected cell and its counts stay the same.",
        )

    if sel_x is None or sel_y is None:
        st.info(
            f"Select a {md(fmap.x_col)} range and a {md(fmap.y_col)} range to inspect "
            "examples, or click a cell on the map."
        )
        return None

    stats = fmap.cell(sel_x, sel_y)
    where = f"**{md(fmap.x_bins.describe(sel_x, fmap.x_col))}** and **{md(fmap.y_bins.describe(sel_y, fmap.y_col))}**"
    if stats.total == 0:
        st.info(f"No examples in this group: {where}.")
        return stats

    mapped_rate = float(fmap.rows["is_error"].mean())
    st.markdown(
        f"{where}: **{plural(stats.errors, 'error')} out of {plural(stats.total, 'example')}** "
        f"({stats.error_rate:.1%} error rate). Across all mapped rows the error rate is {mapped_rate:.1%}."
    )
    if stats.total < settings.small_n:
        st.warning(
            f"Small sample: only {plural(stats.total, 'example')}, so this rate could change "
            "a lot with more data."
        )

    cell_index = fmap.cell_index(sel_x, sel_y)
    if roles.confidence_ok:
        confidence = A.parse_numeric(raw.loc[cell_index, roles.confidence]).values
        means = A.confidence_by_result(confidence, evaluation.rows.loc[cell_index, "is_error"])
        parts = [
            f"{means[key]:.2f} on {word} predictions"
            for key, word in (("error", "wrong"), ("correct", "correct"))
            if means[key] is not None
        ]
        if parts:
            st.caption("Average confidence in this cell: " + ", ".join(parts) + ".")

    shown = fmap.cell_index(sel_x, sel_y, errors_only=errors_only)
    if errors_only and len(shown) == 0:
        st.info("This cell has no errors. Turn off “Errors only” to see its rows.")
    else:
        table = show_rows(raw, evaluation, shown, roles, lead=(fmap.x_col, fmap.y_col), numeric=numeric)
        suffix = " (errors only)" if errors_only else ""
        st.caption(f"Showing {len(shown):,} of the cell's {plural(stats.total, 'row')}{suffix}.")
        st.download_button(
            "Download these rows as CSV",
            table.to_csv(index=False).encode("utf-8"),
            file_name=f"failure_atlas_cell_{sel_x + 1}_{sel_y + 1}.csv",
            mime="text/csv",
            on_click="ignore",
        )
    with st.expander("Class mix in this cell"):
        st.caption("A cell's error rate can reflect which classes land in it.")
        st.dataframe(
            percent_table(A.class_breakdown(evaluation.rows.loc[cell_index]), "error rate"),
            hide_index=True,
            column_config={"error rate": percent_column()},
        )
    return stats


def consistency_footer(
    overview: A.Overview, fmap: A.FailureMap | None, selection: tuple, stats: A.CellStats | None
) -> None:
    checks = A.consistency_checks(overview, fmap)
    if fmap is not None and stats is not None:
        sel_x, sel_y = selection
        checks += [
            ("Selected cell: rows listed = examples on the map", len(fmap.cell_index(sel_x, sel_y)) == stats.total),
            (
                "Selected cell: error rows listed = errors on the map",
                len(fmap.cell_index(sel_x, sel_y, errors_only=True)) == stats.errors,
            ),
        ]
    failed = [name for name, ok in checks if not ok]
    if failed:
        st.error("Internal consistency check failed: " + "; ".join(failed) + ". Please report this.")
    with st.expander(f"Consistency checks: {'all passed' if not failed else f'{len(failed)} failed'}"):
        st.markdown("\n".join(f"* {'✅' if ok else '❌'} {name}" for name, ok in checks))


