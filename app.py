# Error rate is a magnitude, so it gets one hue from light to dark: steps
# 100-700 of a blue ramp, spread evenly over a fixed 0-100% domain. Dark
# themes flip the anchor so a higher rate is always the more prominent cell.
BLUE_RAMP = [
    "#cde2fb", "#b7d3f6", "#9ec5f4", "#86b6ef", "#6da7ec", "#5598e7", "#3987e5",
    "#2a78d6", "#256abf", "#1c5cab", "#184f95", "#104281", "#0d366b",
]
INK, WHITE, MUTED = "#0b0b0b", "#ffffff", "#898781"
EMPTY_FILL = "rgba(137, 135, 129, 0.16)"  # neutral wash that works on light and dark
DIAGONAL_FILL = "background-color: rgba(137, 135, 129, 0.18); font-weight: 600"
TEXT_FLIP = 0.58  # from ramp step 450 on, white text contrasts better than ink
MAX_MATRIX_CLASSES = 30

CSV_HELP = """
One row per evaluated example, with a header row. For example:

```text
image_id,actual,predicted,confidence,brightness,blur_px
img_00001,stop,no_entry,0.43,0.21,6.4
img_00002,yield,yield,0.91,0.77,1.2
```

* **Actual and predicted labels**: any column names; you choose them after uploading.
* **At least two numeric feature columns** to use as the map's axes.
* Optional: an ID column and a confidence column (the probability the model
  gave to the class it predicted, between 0 and 1).
"""


@dataclass(frozen=True)
class Settings:
    n_bins: int
    small_n: int


@dataclass(frozen=True)
class Roles:
    actual: str
    predicted: str
    ids: tuple[str, ...]
    confidence: str | None  # the column picked as confidence, confirmed or not
    confidence_ok: bool  # confirmed as predicted-class probability and within 0-1

    @property
    def reserved(self) -> dict[str, str]:
        """Columns that already have a role, so they can't be map axes."""
        reserved = {self.actual: "actual label", self.predicted: "predicted label"}
        reserved.update({column: "identifier" for column in self.ids})
        if self.confidence:
            reserved[self.confidence] = "confidence"
        return reserved


def md(text: object) -> str:
    """Escape text from the CSV so Markdown never reformats it."""
    return re.sub(r"([\\`*_{}\[\]()#+\-.!|$<>~])", r"\\\1", str(text))


def plural(n: int, word: str) -> str:
    return f"{n:,} {word if n == 1 else word + 's'}"


def percent_table(frame: pd.DataFrame, *columns: str) -> pd.DataFrame:
    """Rates (0-1) as percentages, for tables that show them to one decimal place."""
    return frame.assign(**{column: frame[column] * 100 for column in columns})


def percent_column(label: str | None = None):
    return st.column_config.NumberColumn(label, format="%.1f%%")


def theme_is_dark() -> bool:
    try:
        return st.context.theme.type == "dark"
    except Exception:  # no browser context, e.g. in tests
        return False


# The cache is shared by every visitor to a deployed app, so keep it small.
@st.cache_data(show_spinner=False, max_entries=4, ttl="1h")
def load(data: bytes) -> A.LoadedCSV:
    return A.load_csv(data)


