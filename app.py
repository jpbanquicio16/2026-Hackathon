def style_confusion(confusion: pd.DataFrame):
    def diagonal(frame: pd.DataFrame) -> pd.DataFrame:
        styles = pd.DataFrame("", index=frame.index, columns=frame.columns)
        for label in frame.index:
            if label in frame.columns:
                styles.loc[label, label] = DIAGONAL_FILL
        return styles

    return confusion.style.apply(diagonal, axis=None)


def overview_section(
    raw: pd.DataFrame, evaluation: A.Evaluation, overview: A.Overview, roles: Roles, numeric: tuple[str, ...]
) -> None:
    st.header("2 · Overall performance", divider="gray")
    tiles = st.columns(5)
    tiles[0].metric("Accuracy", f"{overview.accuracy:.1%}", border=True, help="Correct predictions ÷ evaluated rows.")
    tiles[1].metric(
        "Errors", f"{overview.n_errors:,}", border=True,
        help="Rows whose predicted label differs from the actual label.",
    )
    tiles[2].metric("Correct", f"{overview.n_correct:,}", border=True)
    tiles[3].metric(
        "Evaluated rows", f"{overview.n_evaluated:,}", border=True,
        help="Rows with both an actual and a predicted label: the denominator for accuracy.",
    )
    tiles[4].metric(
        "Excluded rows", f"{evaluation.n_excluded:,}", border=True,
        help="Rows missing a label. They are left out of every number on this page.",
    )
    st.caption(
        f"Accuracy = {overview.n_correct:,} correct ÷ {overview.n_evaluated:,} evaluated rows "
        f"(error rate {overview.error_rate:.1%}). Every row counts equally."
    )

    n_classes = len(overview.confusion)
    if n_classes > MAX_MATRIX_CLASSES and n_classes > 0.2 * overview.n_evaluated:
        st.warning(
            f"There are {n_classes:,} distinct labels. This app is built for classification; "
            "if these are continuous values, check the label columns."
        )

    left, right = st.columns([3, 2], gap="large")
    with left:
        st.subheader("Confusion matrix")
        if n_classes > MAX_MATRIX_CLASSES:
            st.info(f"{n_classes:,} classes are too many to show as a matrix. See the most common mistakes.")
        else:
            st.caption(
                "Rows are the actual class, columns the predicted class. "
                "The shaded diagonal counts correct predictions."
            )
            st.dataframe(style_confusion(overview.confusion))
        if overview.predicted_only:
            st.caption(
                "Predicted but never an actual label here: "
                + ", ".join(f"“{md(c)}”" for c in overview.predicted_only) + "."
            )
        if overview.never_predicted:
            st.caption(
                "Actual classes the model never predicted: "
                + ", ".join(f"“{md(c)}”" for c in overview.never_predicted) + "."
            )
    with right:
        st.subheader("Most common mistakes")
        mistakes = A.top_confusions(overview, limit=6)
        if mistakes.empty:
            st.success("No mistakes: every evaluated prediction is correct.")
        else:
            st.dataframe(
                percent_table(mistakes, "share of errors"),
                hide_index=True,
                column_config={
                    "errors": st.column_config.NumberColumn(format="%d"),
                    "share of errors": percent_column(),
                },
            )

    error_index = evaluation.rows.index[evaluation.rows["is_error"]]
    with st.expander(f"All {plural(len(error_index), 'error')}"):
        show_rows(raw, evaluation, error_index, roles, lead=(), numeric=numeric)


